<script setup lang="ts">
import { computed } from 'vue'

const props = withDefaults(
  defineProps<{
    size?: number | string
  }>(),
  { size: 18 }
)

const px = computed(() => {
  const n = typeof props.size === 'number' ? props.size : Number.parseFloat(String(props.size))
  const base = Number.isFinite(n) && n > 0 ? n : 18
  return Math.round(base * 1.2 * 10) / 10
})
</script>

<template>
  <svg
    class="marketplace-icon"
    xmlns="http://www.w3.org/2000/svg"
    viewBox="0 0 24 24"
    :width="px"
    :height="px"
    fill="none"
    stroke="currentColor"
    stroke-width="1.8"
    stroke-linecap="round"
    stroke-linejoin="round"
    aria-hidden="true"
    focusable="false"
  >
    <rect x="3" y="3" width="7.5" height="7.5" rx="1.8" />
    <rect x="3" y="13.5" width="7.5" height="7.5" rx="1.8" />
    <rect x="13.5" y="13.5" width="7.5" height="7.5" rx="1.8" />
    <rect x="14" y="2.5" width="7.2" height="7.2" rx="1.8" transform="rotate(14 17.6 6.1)" />
  </svg>
</template>

<style scoped>
.marketplace-icon {
  display: block;
  flex: none;
  color: var(--text, currentColor);
  pointer-events: none;
}
